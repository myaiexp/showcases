// A million rows in DuckDB, drawn by EmbeddingViewMosaic straight from SQL
import { EmbeddingViewMosaic } from 'embedding-atlas';
import type { Mount } from '@/types.ts';
import { createStage } from '../../shared/stage.ts';
import { readout } from '../../shared/controls.ts';

const mount: Mount = async (el, ctx) => {
  const stage = createStage(el, ctx, { hint: 'The rows were generated by DuckDB itself.' });
  const rows = stage.preview ? 100_000 : 1_000_000;
  const mosaic = await stage.mosaic();
  const t0 = performance.now();

  // Eight spiral arms of noisy points, built in SQL with range() and random().
  const table = 'arms_' + Math.random().toString(36).slice(2, 8);
  await mosaic.exec(`CREATE TABLE "${table}" AS
    SELECT i % 8 AS arm,
           (0.3 + 4 * r) * cos(r * 5 + (i % 8) * pi() / 4) + 0.25 * sqrt(-2 * ln(1 - random())) * cos(2 * pi() * random()) AS x,
           (0.3 + 4 * r) * sin(r * 5 + (i % 8) * pi() / 4) + 0.25 * sqrt(-2 * ln(1 - random())) * cos(2 * pi() * random()) AS y
    FROM (SELECT range AS i, random() AS r FROM range(${rows}))`);
  stage.onDispose(() => void mosaic.exec(`DROP TABLE IF EXISTS "${table}"`));
  if (stage.disposed) return stage.dispose;
  if (!stage.preview) readout(stage.box, `${rows.toLocaleString()} rows created in DuckDB in ${Math.round(performance.now() - t0)} ms`);

  const view = new EmbeddingViewMosaic(stage.view, {
    coordinator: mosaic.coordinator,
    table,
    x: 'x',
    y: 'y',
    category: 'arm',
    width: stage.width,
    height: stage.height,
    config: { colorScheme: 'dark' },
  });
  stage.own(view);

  if (stage.preview) stage.loop((_, t) => view.update({ viewportState: { x: 0, y: 0, scale: 0.2 + 0.1 * Math.sin(t / 2) } }));
  return stage.dispose;
};

export default mount;
